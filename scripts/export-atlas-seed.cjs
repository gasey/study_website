// Reproducible identity manifest for the existing static chapters; no topic inference.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const root=path.resolve(__dirname,'..'),ts=require(root+'/web/node_modules/typescript');
const files=new Map(),loaded=new Map();
function read(p){p=path.resolve(p);if(!p.endsWith('.ts'))p+='.ts';if(loaded.has(p))return loaded.get(p);const source=fs.readFileSync(p,'utf8');files.set(path.relative(root,p),crypto.createHash('sha256').update(source).digest('hex'));const m={exports:{}};loaded.set(p,m.exports);new Function('module','exports','require',ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText)(m,m.exports,id=>{if(!id.startsWith('.'))throw Error('Unexpected runtime import '+id);return read(path.resolve(path.dirname(p),id))});return m.exports}
const {chapters}=read(root+'/web/src/atlas/data/index.ts');
const rows=chapters.map((body,position)=>({body,position,hash:crypto.createHash('sha256').update(JSON.stringify(body)).digest('hex')}));
const sql=`-- Existing site content copied without inferred topic bindings or new source review.
-- Generated by scripts/export-atlas-seed.cjs; do not edit by hand.
BEGIN;
DO $seed$ DECLARE c jsonb; BEGIN
 FOR c IN SELECT value FROM jsonb_array_elements($corpus$${JSON.stringify(rows)}$corpus$::jsonb) LOOP
  INSERT INTO atlas_chapters(id,status,current_version,position) VALUES(c->'body'->>'id','published',1,(c->>'position')::int);
  INSERT INTO atlas_chapter_versions(chapter_id,revision,body,body_hash,attribution,note)
   VALUES(c->'body'->>'id',1,c->'body',c->>'hash','current-site-content','Existing site content; migrated unchanged, no new source or independent review.');
  INSERT INTO atlas_chapter_events(chapter_id,action,revision,detail)
   VALUES(c->'body'->>'id','seed',1,'{"attribution":"current-site-content","new_source_review":false}');
 END LOOP;
END $seed$;
COMMIT;
`;
const target=root+'/api/migrations/0118_atlas_current_site_seed.sql';
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==sql)throw Error('Atlas seed differs from source corpus')}else fs.writeFileSync(target,sql);
console.log('Atlas seed:',rows.length,'unchanged current-site chapters; no topic bindings.');
