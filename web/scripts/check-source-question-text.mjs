import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import {createRequire} from 'node:module'
const require=createRequire(new URL('../package.json',import.meta.url))
const ts=require('typescript'),React=require('react'),{renderToStaticMarkup}=require('react-dom/server')
const source=readFileSync(new URL('../src/components/SourceQuestionText.tsx',import.meta.url),'utf8')
const js=ts.transpileModule(source,{compilerOptions:{jsx:ts.JsxEmit.ReactJSX,module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText
const mod={exports:{}};new Function('require','module','exports',js)(require,mod,mod.exports)
const text=(text)=>renderToStaticMarkup(React.createElement(mod.exports.SourceQuestionText,{text}))
const context=(props)=>renderToStaticMarkup(React.createElement(mod.exports.SourceQuestionContext,props))
const mixed=text('The __*Bible*__ is **important**, ***really***. Fill ___ and _____.')
assert.match(mixed,/<u[^>]*><em>Bible<\/em><\/u>/)
assert.match(mixed,/<strong[^>]*>important<\/strong>/)
assert.match(mixed,/<strong[^>]*><em>really<\/em><\/strong>/)
assert.equal((mixed.match(/source-question-blank/g)||[]).length,2)
assert.doesNotMatch(mixed,/\*|_{2,}/)
assert.match(text('**a __key__ point** and *another*'),/<strong[^>]*>a <u[^>]*>key<\/u> point<\/strong> and <em>another<\/em>/)
assert.doesNotMatch(text('___ then ____'),/<u|<em|<strong/)
assert.match(text('<img src=x onerror=alert(1)>'),/&lt;img/)
assert.match(text('Name the <u>underlined phrase</u>.'),/<u[^>]*>underlined phrase<\/u>/)
assert.match(text('<b>bold</b> and <strong>strong</strong>'),/<strong[^>]*>bold<\/strong> and <strong[^>]*>strong<\/strong>/)
assert.match(text('<i>italic</i> and <em>emphasis</em>'),/<em[^>]*>italic<\/em> and <em[^>]*>emphasis<\/em>/)
assert.match(text('<u><i>nested</i> <b>target</b></u>'),/<u[^>]*><em[^>]*>nested<\/em> <strong[^>]*>target<\/strong><\/u>/)
assert.match(text('<b>outer <b>inner</b> end</b>'),/<strong[^>]*>outer <strong[^>]*>inner<\/strong> end<\/strong>/)
assert.match(text('<u>**important** word</u>'),/<u[^>]*><strong[^>]*>important<\/strong> word<\/u>/)
assert.match(text('<mark>highlighted target</mark><br>Next line'),/<mark[^>]*>highlighted target<\/mark><br\/>Next line/)
assert.match(text('<u onclick="alert(1)">unsafe attributes</u>'),/&lt;u onclick=/)
assert.doesNotMatch(text('<u onclick="alert(1)">unsafe attributes</u>'),/<u onclick=/)
assert.match(text('<script>alert(1)</script>'),/&lt;script&gt;/)
assert.match(text('<u>unclosed'),/&lt;u&gt;unclosed/)
assert.match(text('2 < 3 and 5 > 4'),/2 &lt; 3 and 5 &gt; 4/)
assert.match(text('__'+('long phrase '.repeat(12)).trim()+'__'),/<u[^>]*>long phrase/)
assert.match(context({direction:'Read **carefully**.',passage:'A __*marked*__ passage.'}),/<details[^>]*open=""/)
assert.match(context({passage:'A __*marked*__ passage.'}),/<u[^>]*><em>marked<\/em><\/u>/)
assert.doesNotMatch(context({passage:'Still readable',collapsed:true}),/open=/)
assert.equal(context({}),'')
for(let i=0;i<20;i++)assert.equal(text('End __word__ then ___.'),text('End __word__ then ___.'))
console.log('Source question checks passed: blanks, nested underline/italic/bold, passages, escaping and repeated renders.')
